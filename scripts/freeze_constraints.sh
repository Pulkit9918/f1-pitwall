#!/usr/bin/env bash
# Regenerate constraints/*.txt (exact versions) from the three local venvs.
# Run from anywhere:  bash scripts/freeze_constraints.sh
# After a deliberate upgrade in a venv, re-run this and commit the changed constraints files.
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p constraints
for pair in ingest:f1-pitwall app:f1-app dbt:f1-dbt; do
  name=${pair%%:*}; venv=${pair##*:}
  py="$HOME/.venvs/$venv/bin/pip"
  [ -x "$py" ] || { echo "missing venv: $venv" >&2; exit 1; }
  {
    echo "# Exact versions of ~/.venvs/$venv, generated by scripts/freeze_constraints.sh. Do not edit by hand."
    "$py" freeze
  } > "constraints/$name.txt"
  echo "constraints/$name.txt: $(grep -vc '^#' "constraints/$name.txt") packages"
done
